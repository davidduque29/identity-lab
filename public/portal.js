async function api(action, data) {
  const response = await fetch('/api/lab?action=' + action, {
    method: data ? 'POST' : 'GET',
    credentials: 'same-origin',
    cache: 'no-store',
    headers: data ? { 'Content-Type': 'application/json' } : {},
    body: data ? JSON.stringify(data) : undefined,
  });
  const result = await response.json();
  if (!response.ok) {
    const e = new Error(result.error || 'No se pudo completar la operación.');
    Object.assign(e, result);
    throw e;
  }
  return result;
}
function textNode(tag, text) {
  const e = document.createElement(tag);
  e.textContent = text;
  return e;
}
function message(text) {
  byId('portalStatus').textContent = text;
}
const date = (value) => (value ? new Date(value).toLocaleString('es-CO') : '—');
async function createQr(mode) {
  clearTimeout(pollTimer);
  byId('qrPanel').hidden = false;
  byId('qrState').textContent = 'Preparando sesión…';
  try {
    const qr = await api('qr', { mode });
    byId('qrTitle').textContent =
      mode === 'register' ? 'Regístrate desde el celular' : 'Verifica desde el celular';
    // The SVG is generated by our own QR encoder on the server, never provider/user markup.
    byId('qrImage').replaceChildren(
      new DOMParser().parseFromString(qr.svg, 'image/svg+xml').documentElement,
    );
    byId('qrLink').href = qr.link;
    async function poll() {
      try {
        const s = await api('qr-status&id=' + encodeURIComponent(qr.id));
        const labels = {
          pending: 'Esperando que escanees el QR.',
          claimed: 'Sesión abierta en el celular.',
          registered: 'Registro guardado correctamente.',
          finished: 'Verificación finalizada.',
          expired: 'QR vencido. Genera otro para continuar.',
        };
        byId('qrState').textContent = labels[s.status] + ' Vence: ' + date(qr.expiresAt);
        if (!['finished', 'expired', 'registered'].includes(s.status))
          pollTimer = setTimeout(poll, 3000);
      } catch (e) {
        byId('qrState').textContent = e.message;
      }
    }
    await poll();
    byId('qrPanel').scrollIntoView({ behavior: 'smooth', block: 'center' });
  } catch (e) {
    byId('qrState').textContent = e.message;
  }
}
function avatarElement(avatar) {
  if (avatar.kind === 'upload') {
    const image = new Image();
    image.src = '/api/lab?action=avatar&v=' + Date.now();
    image.alt = 'Avatar administrativo';
    return image;
  }
  return document.createTextNode(avatar.value);
}
function renderAvatar(avatar) {
  byId('avatarPreview').replaceChildren(avatarElement(avatar));
  byId('headerAvatar').replaceChildren(avatarElement(avatar));
  byId('avatarGrid').replaceChildren();
  presets.forEach((value, i) => {
    const button = textNode('button', value);
    button.type = 'button';
    button.setAttribute('aria-label', 'Avatar ' + (i + 1) + ' ' + value);
    button.setAttribute(
      'aria-pressed',
      String(avatar.kind === 'preset' && avatar.value === value),
    );
    button.onclick = () => saveAvatar({ kind: 'preset', value });
    byId('avatarGrid').append(button);
  });
}
let savingAvatar = false;
async function saveAvatar(data) {
  if (savingAvatar) return;
  savingAvatar = true;
  byId('avatarStatus').textContent = 'Guardando avatar…';
  try {
    const r = await api('avatar', data);
    renderAvatar(r.avatar);
    byId('avatarStatus').textContent = 'Avatar guardado.';
  } catch (e) {
    byId('avatarStatus').textContent = e.message;
  } finally {
    savingAvatar = false;
  }
}
async function resizeAvatar(file) {
  if (
    !file ||
    !['image/jpeg', 'image/png', 'image/webp'].includes(file.type) ||
    file.size > 10000000
  )
    throw new Error('Selecciona una imagen de hasta 10 MB.');
  const bitmap = await createImageBitmap(file),
    canvas = document.createElement('canvas');
  canvas.width = 256;
  canvas.height = 256;
  const size = Math.min(bitmap.width, bitmap.height);
  canvas
    .getContext('2d')
    .drawImage(
      bitmap,
      (bitmap.width - size) / 2,
      (bitmap.height - size) / 2,
      size,
      size,
      0,
      0,
      256,
      256,
    );
  bitmap.close();
  return canvas.toDataURL('image/jpeg', 0.86);
}
async function showProfile(p, id) {
  const dl = document.createElement('dl');
  for (const [label, value] of [
    ['Nombre', [p.firstName, p.middleName, p.lastName].filter(Boolean).join(' ')],
    ['Documento', p.documentType + ' ' + p.documentNumber],
    ['Nacimiento', p.birthDate],
    ['Dirección', p.address],
    ['Consentimiento', p.consent?.at],
  ])
    dl.append(textNode('dt', label), textNode('dd', value || '—'));
  byId('profileDetailBody').replaceChildren(dl);
  try {
    const details = await api('admin-profile&id=' + encodeURIComponent(id));
    const image = new Image();
    image.src = '/api/lab?action=reference-photo&id=' + encodeURIComponent(id);
    image.alt = 'Referencia facial registrada';
    image.className = 'reference-preview';
    const technical = document.createElement('details'),
      title = textNode('summary', 'Plantilla facial y datos técnicos (administración)');
    technical.append(
      title,
      textNode(
        'p',
        'Modelo: ' +
          details.biometric.model +
          ' · versión ' +
          details.biometric.schemaVersion +
          ' · fotos guardadas: ' +
          details.referenceCount,
      ),
    );
    const vector = textNode(
      'pre',
      JSON.stringify(details.biometric.descriptors, null, 2),
    );
    vector.className = 'admin-vector';
    technical.append(vector);
    byId('profileDetailBody').append(image, technical);
  } catch (error) {
    byId('profileDetailBody').append(textNode('p', error.message));
  }

  byId('profileDetail').showModal();
}
function renderUsers() {
  const search = byId('userSearch').value.toLowerCase();
  byId('usersRows').replaceChildren();
  for (const u of adminData.users) {
    const p = u.data,
      name = [p.firstName, p.middleName, p.lastName].filter(Boolean).join(' ');
    if (!JSON.stringify(p).toLowerCase().includes(search)) continue;
    const row = document.createElement('tr');
    [
      name,
      p.documentType + ' ' + p.documentNumber,
      u.status === 'deleting'
        ? 'Eliminación pendiente'
        : u.locked_until > Date.now()
          ? 'En pausa'
          : 'Activo',
      String(u.failures),
      u.locked_until > Date.now() ? date(u.locked_until) : '—',
      date(u.created_at),
    ].forEach((v) => row.append(textNode('td', v)));
    const actions = document.createElement('td');
    const detail = textNode('button', 'Ver datos');
    detail.className = 'secondary';
    detail.onclick = () => showProfile(p, u.id);
    actions.append(detail);
    for (const [action, label] of [
      ...(u.referenceCount > 1 ? [['compact-reference', 'Conservar solo 1 foto']] : []),
      ['unlock', 'Desbloquear'],
      [
        'allow-update',
        u.update_allowed ? 'Actualización autorizada' : 'Autorizar actualización',
      ],
      ['delete', 'Eliminar'],
    ]) {
      const button = textNode('button', label);
      button.className = 'secondary';
      button.disabled = action === 'allow-update' && !!u.update_allowed;
      button.onclick = async () => {
        const reason = prompt(label + ': escribe el motivo (mínimo 5 caracteres).');
        if (!reason) return;
        if (
          action === 'delete' &&
          !confirm('Se eliminarán el perfil, las tres fotos y los vectores. ¿Continuar?')
        )
          return;
        button.disabled = true;
        try {
          await api(action, { id: u.id, reason });
          await refreshAdmin();
          message('Operación registrada: ' + label);
        } catch (e) {
          message(e.message);
          button.disabled = false;
        }
      };
      actions.append(button);
    }
    row.append(actions);
    byId('usersRows').append(row);
  }
  if (!byId('usersRows').children.length) {
    const tr = document.createElement('tr'),
      td = textNode('td', 'No hay usuarios para mostrar en esta página.');
    td.colSpan = 7;
    tr.append(td);
    byId('usersRows').append(tr);
  }
}
async function refreshAdmin() {
  byId('refreshAdmin').disabled = true;
  try {
    adminData = await api('admin&offset=' + pageOffset);
    byId('usersCount').textContent =
      adminData.total + ' personas · desde ' + (pageOffset + 1);
    renderUsers();
    byId('eventsRows').replaceChildren();
    for (const e of adminData.events) {
      const p = e.payload,
        r = p.result,
        row = document.createElement('tr');
      [
        date(e.created_at),
        e.action + ' / ' + (e.profile_id?.slice(0, 8) || 'Administración'),
        r
          ? (r.match ? 'Coincide' : 'No coincide') +
            (r.similarity !== undefined ? ' · índice ' + r.similarity + '%' : '') +
            ' · distancia ' +
            r.mean.toFixed(6) +
            ' · umbral ' +
            r.threshold +
            ' · distancias ' +
            r.distances.map((d) => d.toFixed(6)).join(' / ')
          : '—',
        p.network?.ip
          ? (p.network.ip.includes(':') ? 'IPv6: ' : 'IPv4: ') + p.network.ip
          : 'No disponible',
        p.reason ||
          (p.rules
            ? 'Máx. ' +
              p.rules.maxFailures +
              ' · pausa ' +
              p.rules.pauseMinutes +
              ' min · umbral ' +
              p.rules.threshold
            : JSON.stringify(p.after || p.kind || '')),
      ].forEach((v) => row.append(textNode('td', v)));
      byId('eventsRows').append(row);
    }
    byId('previousPage').disabled = pageOffset === 0;
    byId('nextPage').disabled =
      adminData.users.length < 50 && adminData.events.length < 100;
  } catch (e) {
    message(e.message);
  } finally {
    byId('refreshAdmin').disabled = false;
  }
}
