byId('rulesForm').onsubmit = async (event) => {
  event.preventDefault();
  const button = event.submitter;
  button.disabled = true;
  try {
    const rules = Object.fromEntries(
      [...new FormData(event.target)].map(([k, v]) => [k, Number(v)]),
    );
    await api('rules', { rules });
    byId('rulesStatus').textContent =
      'Reglas guardadas. Aplican a los siguientes intentos.';
  } catch (e) {
    byId('rulesStatus').textContent = e.message;
  } finally {
    button.disabled = false;
  }
};
byId('purgeEvents').onclick = async () => {
  if (!confirm('¿Eliminar los eventos anteriores al plazo configurado?')) return;
  try {
    const r = await api('purge-events', {});
    byId('rulesStatus').textContent = r.removed + ' eventos eliminados.';
    await refreshAdmin();
  } catch (e) {
    byId('rulesStatus').textContent = e.message;
  }
};
(async () => {
  try {
    const token = new URLSearchParams(location.hash.slice(1)).get('qr');
    if (token) {
      history.replaceState(null, '', location.pathname);
      const claimed = await api('claim', { token });
      location.replace('/index.html?flow=' + claimed.mode + '&paired=1');
      return;
    }
    // Returning to the portal ends the previous browser capture session, not the stored profile.
    await api('end', {});
    context = await api('context');
    byId('userArea').hidden = false;
    byId('adminToggle').hidden = !context.admin;
    message('Sesión autorizada. Elige registrar o verificar.');
    if (context.admin && ['#administracion', '#perfil'].includes(location.hash)) {
      byId('adminArea').hidden = false;
      await refreshAdmin();
      byId(location.hash === '#perfil' ? 'adminProfile' : 'adminArea').scrollIntoView({
        behavior: 'smooth',
        block: 'start',
      });
    }
    if (context.admin) {
      renderAvatar(context.avatar);
      for (const [k, v] of Object.entries(context.rules)) {
        const field = byId('rulesForm').elements.namedItem(k);
        if (field) field.value = v;
      }
    }
  } catch (e) {
    message(e.message);
    if (e.signIn) byId('signIn').hidden = false;
  }
})();
window.addEventListener('pagehide', () => clearTimeout(pollTimer));

